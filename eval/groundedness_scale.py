"""근거지지도 사람 라벨의 분해 척도와 결합 규칙.

## 왜 분해하는가

`label_scale.py`(관련성)와 같은 이유다. 1~5점을 직접 물으면 라벨하는 사람이 척도를
머릿속에서 만들어야 하고, 그 척도가 항목마다 흔들린다. 두 개의 **범위 대조 질문**으로
쪼개고 환산은 코드가 한다.

근거지지도에서는 쪼개는 이유가 하나 더 있다. **관측된 환각이 한 유형에 몰려 있다.**

    원문: "가민의 웨어러블 부문 매출은 증가했다"
    fact: "가민의 웨어러블 부문 매출은 전년 대비 17.4% 증가했다"

주장은 원문에 있고 **수치만 없다.** 한 점수로 뭉치면 이 유형이 3점 근처에 묻혀
"애매한 것"으로 처리된다. 쪼개면 `①예 ②없음 → 2점(기각)`으로 규칙에 박힌다.

`Cited but Not Verified`(arXiv:2605.06635)가 보고한 간격 — Relevant 판정은 80%를
넘는데 Fact Check는 39~77% — 이 이 유형이다. 사람이 봐도 "주제에 맞는 그럴듯한 문장"
이라서 축을 나누지 않으면 잡히지 않는다.

## 두 질문

    ① 핵심 주장이 원문에 있는가?              예 / 부분 / 아니오
    ② 구체 수치·고유명사가 원문에 있는가?     있음 / 일부 / 없음 / 해당없음

②의 "해당없음"은 fact에 대조할 수치·고유명사가 애초에 없는 경우다. 이때는 ①만으로
점수가 정해진다. 이 선택지가 없으면 수치 없는 fact를 "없음"으로 찍어 부당하게
기각시킨다 — 산출물 루브릭에서 "입력이 없어 못 하는 것"을 누락으로 채점할지
논의했던 것과 같은 문제다.

## 결합 규칙의 근거

기존 검증기 루브릭(파이프라인 5절)과 이산 판정 경계(`ACCEPT_MIN_SCORE=4`,
`REJECT_MAX_SCORE=2`)에 맞췄다.

- `①예 ②없음 = 2점`: **기각**이다. 조작된 수치는 그 fact를 기획서 근거로 쓸 수 없게
  만든다. 다만 주장 자체는 원문에 있으므로 전면 조작(1점)과는 구분한다.
- `①아니오 = 전부 1점`: 핵심 주장이 원문에 없으면 수치가 우연히 맞아도 근거가 아니다.
- `①부분 ②일부 = 3점`: **보류**. 사람이 봐도 애매한 자리를 3점에 모은다.
"""

from __future__ import annotations

from typing import Literal

ClaimScope = Literal["예", "부분", "아니오"]
NumericScope = Literal["있음", "일부", "없음", "해당없음"]

# (핵심 주장, 구체 수치·고유명사) → 근거지지도 1~5점
COMBINE: dict[tuple[ClaimScope, NumericScope], int] = {
    ("예",     "있음"):     5,
    ("예",     "일부"):     4,
    ("예",     "없음"):     2,   # ★ 수치 조작 — 가장 위험한 유형
    ("예",     "해당없음"): 5,
    ("부분",   "있음"):     4,
    ("부분",   "일부"):     3,
    ("부분",   "없음"):     2,
    ("부분",   "해당없음"): 3,
    ("아니오", "있음"):     1,
    ("아니오", "일부"):     1,
    ("아니오", "없음"):     1,
    ("아니오", "해당없음"): 1,
}

CLAIM_HELP = {
    "예":     "fact의 핵심 주장이 원문에 그대로, 또는 표현만 다른 같은 뜻으로 있다",
    "부분":   "일부만 원문에 있다. 또는 원문에서 추론은 되지만 명시되지 않았다",
    "아니오": "원문에 없는 주장이다",
}

NUMERIC_HELP = {
    "있음":     "fact의 수치·고유명사가 모두 원문에 있다 (표기 차이는 있어도 됨)",
    "일부":     "일부만 원문에 있다",
    "없음":     "원문에 없는 수치·고유명사가 붙어 있다",
    "해당없음": "fact에 대조할 수치·고유명사가 없다",
}

# 판정 경계 — agents/verification.py의 운영 상수와 같은 값이어야 한다.
# 여기에 복사해 두는 대신 import 하는 것이 옳지만, 이 모듈은 라벨링 UI 생성에도
# 쓰여 agents 패키지 의존성을 만들지 않으려고 상수 검증만 테스트로 묶었다.
ACCEPT_MIN_SCORE = 4
REJECT_MAX_SCORE = 2


def combine(claim: ClaimScope, numeric: NumericScope) -> int:
    """두 범위 판정을 근거지지도 1~5점으로 환산한다."""
    try:
        return COMBINE[(claim, numeric)]
    except KeyError:
        raise ValueError(f"알 수 없는 조합: claim={claim!r} numeric={numeric!r}") from None


def status_of(score: int) -> str:
    """점수를 운영과 같은 규칙으로 판정 문자열로 바꾼다."""
    if score >= ACCEPT_MIN_SCORE:
        return "채택"
    if score <= REJECT_MAX_SCORE:
        return "기각"
    return "보류"
